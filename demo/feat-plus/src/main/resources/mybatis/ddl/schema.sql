-- Feat Plus 表结构
--
-- 统一约定：每张表都必须具备 is_deleted / created_time / edit_time / creator / editor 五个审计字段。
-- creator、editor 存操作人的 sys_user.id；系统自动产生或初始化数据留 NULL。

CREATE TABLE IF NOT EXISTS sys_role (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL,
    name VARCHAR(64) NOT NULL,
    description VARCHAR(256) NOT NULL DEFAULT '',
    -- 权限点以英文逗号分隔，如 user:read,user:write；空串表示登录后没有任何业务权限。
    permissions VARCHAR(512) NOT NULL DEFAULT '',
    -- 数据范围：1 全部 / 2 自定义部门 / 3 本部门 / 4 本部门及以下 / 5 仅本人。
    -- 一个账号挂多个角色时取最宽的一档，见 AccessGuard。
    department_scope SMALLINT NOT NULL DEFAULT 1,
    -- 内置角色（ADMIN / DEPT_MANAGER / AUDITOR / USER）：编码不可改、不可删除；ADMIN 的权限也不可改。
    builtin SMALLINT NOT NULL DEFAULT 0,
    status SMALLINT NOT NULL DEFAULT 1,
    is_deleted SMALLINT NOT NULL DEFAULT 0,
    created_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    edit_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    creator BIGINT,
    editor BIGINT
);

-- code 不建唯一约束，理由同 sys_user.username：软删除后同名行仍在表里。
-- 唯一性由 RoleService 在应用层校验，范围限定 is_deleted = 0。

CREATE TABLE IF NOT EXISTS sys_department (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 0 表示根部门。用 0 而不是 NULL，避免 WHERE parent_id = ? 时 NULL 不参与比较。
    parent_id BIGINT NOT NULL DEFAULT 0,
    code VARCHAR(32) NOT NULL DEFAULT '',
    name VARCHAR(64) NOT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    description VARCHAR(256) NOT NULL DEFAULT '',
    status SMALLINT NOT NULL DEFAULT 1,
    is_deleted SMALLINT NOT NULL DEFAULT 0,
    created_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    edit_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    creator BIGINT,
    editor BIGINT
);

CREATE TABLE IF NOT EXISTS sys_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    display_name VARCHAR(64) NOT NULL,
    -- 角色不在这里：一个人可以同时是「部门主管」和「审计员」，关系记在 sys_user_role。
    -- 部门用主键关联 sys_department.id：部门改名后所有成员自动跟随，不会残留旧名称。
    department_id BIGINT,
    email VARCHAR(128) NOT NULL DEFAULT '',
    status SMALLINT NOT NULL,
    is_deleted SMALLINT NOT NULL DEFAULT 0,
    created_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    edit_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    creator BIGINT,
    editor BIGINT
);

-- username 不再建唯一约束：软删除后同名账号仍留在表里，唯一索引会让「删了再建」直接失败。
-- 唯一性由 UserService.assertUnique 在应用层保证，且只在 is_deleted = 0 的范围内比较。

-- 用户与角色的多对多关系。
-- 关联用 role_code 而不是 role_id，与 sys_user 原来的约定一致：编码是权限判定的锚点，
-- 角色编码本身不允许修改，所以不会出现「改了编码关联全断」的问题。
-- 一个人挂多个角色时，权限点取并集、数据范围取最宽，见 AccessGuard。
CREATE TABLE IF NOT EXISTS sys_user_role (
    user_id BIGINT NOT NULL,
    role_code VARCHAR(32) NOT NULL,
    is_deleted SMALLINT NOT NULL DEFAULT 0,
    created_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    edit_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    creator BIGINT,
    editor BIGINT,
    PRIMARY KEY (user_id, role_code)
);

-- 数据范围取「自定义」时，角色能看到哪些部门。与其他表一样存编码，理由同上。
CREATE TABLE IF NOT EXISTS sys_role_dept (
    role_code VARCHAR(32) NOT NULL,
    department_id BIGINT NOT NULL,
    is_deleted SMALLINT NOT NULL DEFAULT 0,
    created_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    edit_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    creator BIGINT,
    editor BIGINT,
    PRIMARY KEY (role_code, department_id)
);

CREATE TABLE IF NOT EXISTS sys_activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind VARCHAR(16) NOT NULL,
    title VARCHAR(128) NOT NULL,
    description VARCHAR(256) NOT NULL,
    user_id BIGINT,
    is_deleted SMALLINT NOT NULL DEFAULT 0,
    created_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    edit_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    creator BIGINT,
    editor BIGINT
);

CREATE TABLE IF NOT EXISTS sys_notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(128) NOT NULL,
    description VARCHAR(256) NOT NULL,
    -- 接收人：0 或 NULL 表示广播（所有人可见），大于 0 表示只投递给这个用户。
    user_id BIGINT,
    is_deleted SMALLINT NOT NULL DEFAULT 0,
    created_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    edit_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    creator BIGINT,
    editor BIGINT
);

-- 已读状态按「用户 × 通知」记录。
-- 不能像以前那样在 sys_notification 上放 read_flag：广播通知只有一行，两个管理员谁点了已读，
-- 另一个人那边也会变成已读。拆成独立的关联表后，每条通知对每个人都有各自的已读状态。
CREATE TABLE IF NOT EXISTS sys_notification_read (
    notification_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    is_deleted SMALLINT NOT NULL DEFAULT 0,
    created_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    edit_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    creator BIGINT,
    editor BIGINT,
    PRIMARY KEY (notification_id, user_id)
);

-- 按天聚合的登录统计，主键是日期，同样带审计字段，但 creator/editor 由系统写入，业务上不做人工编辑。
CREATE TABLE IF NOT EXISTS sys_login_stat (
    stat_date DATE PRIMARY KEY,
    login_count INT NOT NULL DEFAULT 0,
    is_deleted SMALLINT NOT NULL DEFAULT 0,
    created_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    edit_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    creator BIGINT,
    editor BIGINT
);
